"""Generate the casefold exception table in src/rs/util/casefold_table.rs (included by src/rs/util.rs).

Usage: uv run --no-project python -I tools/gen_casefold.py > src/rs/util/casefold_table.rs

Lists every code point where Python's str.casefold() differs from str.lower().
"""

import sys
import unicodedata


def esc(ch: str) -> str:
    return chr(92) + "u{" + format(ord(ch), "x") + "}"


def main() -> None:
    rows = []
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        folded = c.casefold()
        if folded != c.lower():
            rows.append((cp, folded))
    print(f"// @generated by tools/gen_casefold.py (Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}).")
    print("// Code points where str.casefold() != str.lower(), sorted by code point.")
    print("pub(crate) const CASEFOLD_EXCEPTIONS: &[(char, &str)] = &[")
    for cp, folded in rows:
        escaped = "".join(esc(x) for x in folded)
        print(f"    ('{esc(chr(cp))}', \"{escaped}\"),")
    print("];")


main()
